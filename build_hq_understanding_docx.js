H1("议题十　收尾时提出的正式诉求");
Q("如何连接刚训练好的模型？RNP 自己的应用和 agent 能否接入？");
A("通过管理控制台按租户查看，用 API 连接刚训好的模型；自有应用和 agent 通过 MaaS API 接入使用推理算力，但算力有限，不能开放给太多应用。");

Q("国民应用是否运行在华为在巴西建设的算力上？");
A("是，运行在华为算力上，目前设计约 100 PFLOPS，未来可扩展。");

Q("RNP 需要培训计划、责任矩阵和人力规划向 MCTI 申请资金，讯飞能否提供？RNP 将把按工作包组织的项目文件译成英文发给讯飞，讯飞是否配合？");
A("讯飞可以协助起草材料，会对 RNP 的项目文件提意见，并发送交付进度表。");
N("RNP 指出持续预训练从全在巴西改为部分在中国，是一个变化。");

Q("领域模型能否与国家模型同步启动以尽早出成果？能否一开始就向部分开发者开放 API？");
A("可以讨论。中国算力可用于公开数据，敏感数据必须本地处理、需 RNP 协调本地算力；讯飞巴西团队正为政府部门做招聘 agent 的 POC，愿共同确定高优先级领域和资源，尽早取得第一批成果。RNP 强调主权是底线，公开数据不受此限。");

Q("讯飞是否支持像其他项目那样举办学生黑客松以动员社区？");
A("有经验，曾帮企业组织 AI 竞赛；组织者应是 RNP，讯飞核心团队在宣传、品牌、赞助上支持。");

