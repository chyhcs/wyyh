H1("议题九　看真实平台时问的");
Q("平台能否处理表格类数据、批量上传数千个文件、通过 API 直连数据仓库？能接哪些类型的数据源？");
A("支持批量上传和批量分析；有 API，可以开放；特定系统里的数据按原始数据处理；演示环境暂无表格类样例。");

Q("RNP 的数据存放在数据湖以及 SiBBr 这类带元数据的结构化开放数据节点中，平台能否直接接入？JSON、表格、CSV 都有。");
A("可以，做定制适配：改进工具或用小模型适配 RNP 数据，保证平台能连上 RNP 准备好的数据集；已切分的高质量结构化数据可直接导入；在 RNP 许可下从节点抓取。");

Q("平台的输入是否为完全原始的数据？每一步处理是否对 RNP 开放可见？葡语切分工具是否需要定制？");
A("是。每一步处理开放可见，知识转移逐步讲解；工具目前针对英文和中文，葡语切分要与 RNP 语言专家共建，讯飞出技术、RNP 出语言专家；不是黑盒，是讯飞自研。末端形成数据集库，支持持续预训练和 SFT。");

Q("是否有开发者 SDK，让 RNP 在平台之外开发？");
A("不提供平台 SDK。平台是集成工作流，通过 SDK 暴露局部功能可能脱离平台控制、无法保证正常使用，建议在平台内完成。");

Q("新的开源模型如何放进平台训练？RNP 习惯在代码层用 Python 和脚本工作，平台是否把这一层隐藏了？");
A("新模型可以上传，训练框架也可以上传；但模型必须先经华为适配昇腾 NPU，因为不是所有模型都有昇腾训练支持。");

Q("RNP 认为培训人操作高层抽象的平台没有价值，若不能改平台去适配新模型和库就不值得学，他们要的是训练幕后的机制和工作负载为何如此组织，讯飞的知识转移能否给到这一层？");
A("知识转移不只是操作，会讲系统内部的 know-how；顺序是先讲原理，最后才教操作，不掌握原理也用不好平台。");
DEEP("上两问和这一问实质是同一个问题：**讯飞交付的是 RNP 可以打开、改动、替换的工程环境，还是只能按按钮的封闭产品。** 打个比方，平台是一台全自动烹饪机，星火是预装菜谱，RNP 问的是盖子能不能掀开、底下的灶台能不能自己用；他们要的是厨师培训，不是操作员培训。背后的担心是两年后被锁在讯飞平台和星火目录里，与项目\"主权、自主\"的目标相悖。总部回应要分层说清界面层、训练框架层、昇腾适配层各自给什么，RNP 能否脱离平台跑训练，开源模型接入谁做、多久，课程先原理后操作。五月书面答复已承诺交付基座模型的开源框架版结构源码，口径比会上更宽，需对齐。");

