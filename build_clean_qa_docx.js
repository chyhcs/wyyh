let QN = 0, turnsR = 0, turnsX = 0, turnsH = 0;
for (const th of T) {
  if (th.inter) {
    D.push(new Paragraph({ children: [R("插话", { bold: true, size: 21, color: GRAY }), R(`　${th.inter}`, { size: 20, color: GRAY })], spacing: { before: 240, after: 80 }, keepNext: true }));
  } else {
    QN += 1;
    D.push(new Paragraph({ children: [R(`Q${QN}`, { bold: true, size: 24, color: RED }), R(`　${th.topic}`, { bold: true, size: 23 })], spacing: { before: 300, after: 100 }, keepNext: true }));
  }
  th.turns.forEach(([k, t], i) => {
    const [lab, col] = LAB[k];
    if (k === "R") turnsR++; else if (k === "X") turnsX++; else turnsH++;
    D.push(new Paragraph({ children: [R(lab + "：", { bold: true, color: col }), R(t)], spacing: { after: 100, line: 330 }, indent: { left: 600, hanging: 600 }, keepNext: i < th.turns.length - 1 && th.turns.length <= 3 }));
  });
}

