def slide(title):
    return new_slide(prs, LAYOUT, title)


def detail_slide(title):
    s = slide(title)
    chip(s, R - 2.0, 0.3, 2.0, 0.3, "详情 · 按需展开", fill=GRAY_T, color=TXT, size=9.5, line=LINE)
    return s


def flow(s, y, h, steps, gap=0.25, x=L, w=CW, name_size=13, desc_size=11):
    n = len(steps)
    bw = (w - (n - 1) * gap) / n
    for i, (name, desc) in enumerate(steps):
        bx = x + i * (bw + gap)
        card(s, bx, y, bw, h, fill=REDT if i == 0 else PANEL)
        dot(s, bx + 0.18, y + 0.18, 0.36, str(i + 1))
        text(s, bx + 0.64, y + 0.14, bw - 0.8, 0.44, name, size=name_size, color=TXT, bold=True, valign="m", margin=(0, 0, 0, 0), sa=0)
        body(s, bx + 0.18, y + 0.7, bw - 0.36, h - 0.8, desc, size=desc_size)
        if i < n - 1:
            arrow(s, bx + bw + 0.02, y + 0.26)


def two_party(s, y, h, xf, rnp, x=L, w=CW, gap=0.3, size=11):
    half = (w - gap) / 2
    for i, (name, color, fill, items) in enumerate([("讯飞", RED, REDT, xf), ("RNP", RNP_C, BLUET, rnp)]):
        cx = x + i * (half + gap)
        card(s, cx, y, half, h, fill=fill)
        label(s, cx + 0.25, y + 0.1, 1.5, name, color=color, size=13)
        body(s, cx + 0.25, y + 0.46, half - 0.5, h - 0.52, items, size=size, bullet=True, bcolor=color, sa=2)


def band(s, y, h, title, content, fill=PANEL2, line=LINE, title_w=1.3, size=12):
    card(s, L, y, CW, h, fill=fill, line=line)
    label(s, L + 0.25, y + (h - 0.34) / 2, title_w, title, color=RED, size=12.5)
    body(s, L + 0.25 + title_w, y + 0.08, CW - 0.5 - title_w, h - 0.14, content, size=size, valign="m")


def deliverable_page(title, purpose, steps, xf, rnp, bottom_title, bottom, visual=None):
    s = slide(title)
    band(s, 1.05, 0.66, "用途", purpose, size=11.5)
    label(s, L, 1.88, 3, "怎么做", color=TXT, size=12.5)
    flow(s, 2.22, 1.6, steps)
    label(s, L, 3.98, 3, "谁做什么", color=TXT, size=12.5)
    if visual:
        vw = 3.4
        card(s, L, 4.32, vw, 1.5, fill=PANEL, line=LINE)
        text(s, L + 0.15, 4.32, vw - 0.3, 1.5, visual, size=11, color=MUTE, align="c", valign="m", margin=(0, 0, 0, 0), sa=2)
        two_party(s, 4.32, 1.5, xf, rnp, x=L + vw + 0.3, w=CW - vw - 0.3, size=10.5)
    else:
        two_party(s, 4.32, 1.5, xf, rnp)
    band(s, 6.0, 0.62, bottom_title, bottom, fill=PANEL, line=None, title_w=1.7, size=11.5)
    return s


