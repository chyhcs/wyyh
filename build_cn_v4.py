def appendix_slide(title, question):
    s = slide(title)
    chip(s, R - 3.9, 0.3, 3.9, 0.32, question, fill=WHITE, color=TXT, size=10, line=LINE)
    return s


def flow(s, y, h, steps, gap=0.25, x=L, w=CW, name_size=13, desc_size=11.5):
    """steps: (名称, 一句说明, (标签, 颜色))"""
    n = len(steps)
    bw = (w - (n - 1) * gap) / n
    for i, (name, desc, tag) in enumerate(steps):
        bx = x + i * (bw + gap)
        card(s, bx, y, bw, h, fill=REDT if i == 0 else PANEL)
        dot(s, bx + 0.16, y + 0.16, 0.34, str(i + 1), size=10.5)
        text(s, bx + 0.58, y + 0.12, bw - 0.58 - 1.0, 0.42, name, size=name_size, color=TXT, bold=True, valign="m", margin=(0, 0, 0, 0), sa=0)
        chip(s, bx + bw - 1.05, y + 0.17, 0.92, 0.28, tag[0], fill=tag[1], size=8.5)
        body(s, bx + 0.16, y + 0.68, bw - 0.32, h - 0.78, desc, size=desc_size, ls=1.25)
        if i < n - 1:
            arrow(s, bx + bw + 0.02, y + 0.24)


def two_party(s, y, h, xf, rnp, x=L, w=CW, gap=0.3, size=11.5):
    half = (w - gap) / 2
    for i, (name, color, fill, items) in enumerate([("讯飞做", RED, REDT, xf), ("RNP 做", RNP_C, BLUET, rnp)]):
        cx = x + i * (half + gap)
        card(s, cx, y, half, h, fill=fill)
        label(s, cx + 0.25, y + 0.08, 1.5, name, color=color, size=12.5)
        body(s, cx + 0.25, y + 0.44, half - 0.5, h - 0.5, items, size=size, bullet=True, bcolor=color, sa=3)


def band(s, y, h, title, content, fill=PANEL2, line=LINE, title_w=1.45, size=12, color=RED):
    card(s, L, y, CW, h, fill=fill, line=line)
    label(s, L + 0.25, y + (h - 0.34) / 2, title_w, title, color=color, size=12)
    body(s, L + 0.25 + title_w, y + 0.06, CW - 0.5 - title_w, h - 0.12, content, size=size, valign="m")


